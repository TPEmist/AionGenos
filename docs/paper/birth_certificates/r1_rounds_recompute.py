"""2026-10 POST-HOC recomputation of the D11 data-limitation probe at rounds 1-3.

Status: EXPLORATORY, post-hoc (PI ruling 2026-10-05). The rounds 2-3 values
printed in earlier drafts had no birth certificate and are NOT restored; this
script is the only source for any rounds-1..3 number the paper cites.

Definition (matches the persisted round-1 output, which is used as the
definition check): for arm a, episode k, round r,
    dX[a,k,r] = parsed_left_pos[x] at VLM interaction r  -  left_ee_pos[x] at
                trajectory step r (grid units),
    resid     = dX - mean_k dX (per arm, per round);
    corr      = Pearson(resid[C_retrieval], resid[a]) over episodes paired by
                ep_idx (shared eval seed) that have a valid round r in both.
Null: 2000 permutations of the C_retrieval residuals (seeded), two-sided.

    python3 docs/paper/birth_certificates/r1_rounds_recompute.py \
        > docs/paper/birth_certificates/r1_rounds_recompute.txt
"""
import argparse
import os
import itertools
import json
import math
import random
import re
from pathlib import Path

ARMS_SRC = "scripts/analysis/d11_exploratory.py"   # run/log per arm (read live)
EXPL_JSON = "workspace/d11_audit/exploratory.json"
DISTILLED = ["A_action_only", "B_main", "A_ctrl_rat", "D_gist"]
ROUNDS = (1, 2, 3)
N_PERM = 2000
SEED = 20261005
_EP_RE = re.compile(r"Episode (\d+)/\d+ \| [^|]+\| ([0-9a-f-]+)")


def arm_table(root):
    src = (root / ARMS_SRC).read_text()
    return {a: {"run": r, "log": l} for a, r, l in re.findall(
        r'"(\w+)":\s*\{"run": "(\w+)", "log": "([^"]+)"\}', src)}


def episodes(root, cfg):
    out = {}
    for line in (root / cfg["log"]).read_text().splitlines():
        m = _EP_RE.search(line)
        if not m:
            continue
        idx, eid = int(m.group(1)) - 1, m.group(2)
        for sub in ("success", "failure"):
            p = root / "data/replays" / cfg["run"] / sub / f"{eid}.json"
            if p.exists():
                out[idx] = json.loads(p.read_text())
                break
    return out


def dx(rp, r):
    try:
        tgt = rp["vlm_interactions"][r - 1]["parsed_left_pos"][0]
        if tgt is None:
            return None
        return float(tgt - rp["trajectory"][r - 1]["left_ee_pos"][0])
    except (KeyError, IndexError, TypeError):
        return None


def pearson(x, y):
    n = len(x)
    mx, my = sum(x) / n, sum(y) / n
    sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    sxx = sum((a - mx) ** 2 for a in x)
    syy = sum((b - my) ** 2 for b in y)
    return sxy / math.sqrt(sxx * syy)


def residuals(vals):
    m = sum(vals.values()) / len(vals)
    return {k: v - m for k, v in vals.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=os.environ.get("AIONGENOS_DATA_ROOT"),
                    required="AIONGENOS_DATA_ROOT" not in os.environ,
                    help="AionGenos data root (or set $AIONGENOS_DATA_ROOT)")
    root = Path(ap.parse_args().data_root)
    arms = arm_table(root)
    eps = {a: episodes(root, arms[a]) for a in DISTILLED + ["C_retrieval"]}
    rng = random.Random(SEED)
    persisted = json.loads((root / EXPL_JSON).read_text())["data_limitation_diagnostic"]["corr"]

    print("# r1_rounds_recompute.txt — 2026-10 post-hoc recomputation (EXPLORATORY);")
    print("# generated by r1_rounds_recompute.py; do not hand-edit")
    print(f"# null: {N_PERM} permutations, seed {SEED}\n")
    for r in ROUNDS:
        vals = {a: {k: v for k, rp in eps[a].items() if (v := dx(rp, r)) is not None} for a in eps}
        for a in DISTILLED:
            common = sorted(set(vals["C_retrieval"]) & set(vals[a]))
            rc = residuals({k: vals["C_retrieval"][k] for k in common})
            ra = residuals({k: vals[a][k] for k in common})
            x = [rc[k] for k in common]
            y = [ra[k] for k in common]
            c = pearson(x, y)
            null = []
            for _ in range(N_PERM):
                xs = x[:]
                rng.shuffle(xs)
                null.append(pearson(xs, y))
            p = (1 + sum(abs(v) >= abs(c) for v in null)) / (N_PERM + 1)
            band = sorted(abs(v) for v in null)[int(0.95 * N_PERM) - 1]
            check = f"  persisted_r1={persisted[a]:+.3f}" if r == 1 else ""
            print(f"[round {r}] {a:<14} n={len(common):3d}  r={c:+.3f}  perm_p={p:.3f}"
                  f"  band95=±{band:.3f}{check}")
        # Shared-geometry baseline: distilled arms against EACH OTHER (no
        # retrieval involved) on the same paired episodes.
        base = []
        for a, b in itertools.combinations(DISTILLED, 2):
            common = sorted(set(vals[a]) & set(vals[b]))
            ra = residuals({k: vals[a][k] for k in common})
            rb = residuals({k: vals[b][k] for k in common})
            base.append(pearson([ra[k] for k in common], [rb[k] for k in common]))
        print(f"[round {r}] distilled-vs-distilled baseline: min={min(base):+.3f} max={max(base):+.3f}")


if __name__ == "__main__":
    main()
